const ALPHABET = 'ABCDEFGHJKLMNPQRSTUVWXYZ23456789';

export function randomCode() {
  let code = '';
  for (let i = 0; i < 6; i++) code += ALPHABET[Math.floor(Math.random() * ALPHABET.length)];
  return code;
}

export function normalizeCaptcha(value) {
  return String(value || '')
    .replace(/[۰-۹]/g, (digit) => String('۰۱۲۳۴۵۶۷۸۹'.indexOf(digit)))
    .replace(/[٠-٩]/g, (digit) => String('٠١٢٣٤٥٦٧٨٩'.indexOf(digit)))
    .replace(/\s+/g, '')
    .toUpperCase();
}

export function captchaSvg(code) {
  const width = 348;
  const height = 108;
  const scale = 8;
  const parts = [`<rect width="${width}" height="${height}" fill="#edf3fb"/>`];
  for (let i = 0; i < 3; i++) {
    const y = 18 + i * 28;
    parts.push(`<path d="M 8 ${y} H ${width - 8}" stroke="#d5e2f2" stroke-width="2" fill="none"/>`);
  }
  for (let i = 0; i < code.length; i++) {
    const glyph = FONT[code[i]] || FONT.A;
    const ox = 16 + i * 54;
    const oy = 24;
    glyph.forEach((row, r) => {
      [...row].forEach((bit, c) => {
        if (bit === '1') parts.push(`<rect x="${ox + c * scale}" y="${oy + r * scale}" width="${scale - 1}" height="${scale - 1}" fill="#163b63"/>`);
      });
    });
  }
  return `<svg xmlns="http://www.w3.org/2000/svg" width="${width}" height="${height}" viewBox="0 0 ${width} ${height}">${parts.join('')}</svg>`;
}
